import { readFile, writeFile } from "node:fs/promises";

const source = new URL("./data/canadian-municipalities-2024.json", import.meta.url);
const destination = new URL("../api/migrations/039_cities.sql", import.meta.url);
const municipalities = JSON.parse(await readFile(source, "utf8"));
const extras = {
  Ontario: [
    "Scarborough", "North York", "Etobicoke", "Thornhill", "Woodbridge", "Maple",
    "Unionville", "Willowdale", "Kleinburg", "Nobleton", "Concord", "Stouffville",
    "Agincourt", "Don Mills", "York", "East York", "Rexdale", "Weston", "Malvern", "Port Credit"
  ],
  // The source already contains Montréal, Québec, Trois-Rivières, and Lévis.
  Quebec: ["Montreal", "Quebec City", "Trois-Rivieres", "Levis"]
};
const quote = (value) => `'${value.replaceAll("'", "''")}'`;
const sql = [
  "-- Generated by scripts/generate-cities-seed.mjs; edit the generator, then rerun it.",
  "-- Source: Statistics Canada 2024 Census Subdivision Boundary File, plus listed extras.",
  "CREATE TABLE IF NOT EXISTS public.cities (",
  "  id BIGSERIAL PRIMARY KEY,",
  "  province TEXT NOT NULL,",
  "  name TEXT NOT NULL,",
  "  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),",
  "  CHECK (btrim(name) <> ''),",
  "  CHECK (btrim(province) <> '')",
  ");",
  "CREATE UNIQUE INDEX IF NOT EXISTS cities_province_lower_name_key ON public.cities (province, lower(name));",
  "-- Also enforce duplicates across province casing; supports province-scoped searches.",
  "CREATE UNIQUE INDEX IF NOT EXISTS cities_lower_province_lower_name_key ON public.cities (lower(province), lower(name));",
  ""
];
let total = 0;
for (const [province, names] of Object.entries(municipalities)) {
  const seen = new Set();
  const unique = [...names, ...(extras[province] ?? [])].map((name) => name.trim()).filter((name) => {
    const key = name.toLowerCase();
    if (!name || seen.has(key)) return false;
    seen.add(key);
    return true;
  });
  sql.push(
    `-- ${province}: ${unique.length} names`,
    "INSERT INTO public.cities (province, name) VALUES",
    unique.map((name) => `(${quote(province)},${quote(name)})`).join(",\n"),
    "ON CONFLICT DO NOTHING;",
    ""
  );
  total += unique.length;
}
await writeFile(destination, sql.join("\n"));
console.log(`Generated 039_cities.sql with ${total} cities across ${Object.keys(municipalities).length} provinces/territories.`);
